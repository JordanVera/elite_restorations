import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = "public/images";
const files = [];

function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else if (/\.(jpe?g|png|webp)$/i.test(name)) files.push(full);
  }
}

walk(root);
files.sort();

const entries = [];
for (const file of files) {
  const meta = await sharp(file).metadata();
  const rotated = (meta.orientation ?? 1) >= 5;
  const width = rotated ? meta.height : meta.width;
  const height = rotated ? meta.width : meta.height;
  entries.push([file.replace(/^public/, ""), width, height]);
}

const body = entries
  .map(([src, w, h]) => `  "${src}": { width: ${w}, height: ${h} },`)
  .join("\n");

fs.writeFileSync(
  "src/lib/image-manifest.ts",
  `// Generated by scripts/build-image-manifest.mjs. Do not edit by hand.\nexport const imageManifest: Record<string, { width: number; height: number }> = {\n${body}\n};\n`,
);
console.log(`Wrote ${entries.length} entries`);
